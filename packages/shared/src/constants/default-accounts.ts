/**
 * 每位使用者**註冊時**會自動取得的預設帳戶。
 *
 * 注意種子的時機與分類不同：分類屬於帳本，所以在建立帳本時複製；帳戶屬於使用者，
 * 所以在註冊時建立一次，之後所有帳本共用。
 *
 * **只預設「現金」一個**。「銀行」「信用卡」看似也該預設，但它們是帳戶的*種類*
 * 而非帳戶本身——沒有人的戶頭叫「銀行」，實際存在的是「國泰世華」「台灣銀行」，
 * 各有各的餘額。預設一個叫「銀行」的帳戶，只會逼使用者改名（那預設就沒意義）
 * 或把多家銀行的錢混成一格（那餘額就是假的）。這類帳戶由使用者自行新增。
 *
 * 那為什麼還要預設現金？因為連動帳本的交易必須指定帳戶，一個帳戶都沒有的話，
 * 使用者第一次記帳就會卡住。現金是唯一「人人都有、且真的只有一個」的帳戶。
 *
 * 與預設分類一樣，它被視為「使用者資料」（可改名、可刪除），而非固定的系統值。
 * 初始餘額為 0，使用者可自行調整成導入當下的真實金額。
 */
export const DEFAULT_ACCOUNTS: readonly string[] = ['現金'] as const;
